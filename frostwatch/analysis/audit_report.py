_template = _env.from_string(_HTML)


def _counts(result: AuditResult) -> dict[str, int]:
    c = {"high": 0, "medium": 0, "low": 0, "info": 0}
    for f in result.findings:
        c[f.severity] = c.get(f.severity, 0) + 1
    return c


def render_html(result: AuditResult) -> str:
    return _template.render(
        r=result,
        money=_money,
        counts=_counts(result),
        labels=CATEGORY_LABELS,
        repo=REPO_URL,
        version=__version__,
    )


def render_markdown(result: AuditResult) -> str:
    lines = [
        "# Snowflake Savings Audit" + (" (demo data)" if result.demo else ""),
        "",
        f"**Estimated savings: {_money(result.monthly_savings_usd)}/month "
        f"({_money(result.annual_savings_usd)}/year)** on "
        f"{_money(result.monthly_compute_spend_usd)}/month of warehouse compute. "
        f"Window: last {result.days} days"
        + (f", account `{result.account}`" if result.account else "")
        + ".",
        "",
        "| # | Severity | Finding | Object | Est. saving / mo |",
        "|---|---|---|---|---|",
    ]
    for i, f in enumerate(result.findings, 1):
        saving = _money(f.monthly_savings_usd) if f.monthly_savings_usd else "risk / perf"
        lines.append(f"| {i} | {f.severity} | {f.title} | `{f.object_name}` | {saving} |")
    lines.append("")
    for i, f in enumerate(result.findings, 1):
        lines += [
            f"### {i}. {f.title}: `{f.object_name}`",
            "",
            f"**Why:** {f.evidence}",
            "",
            f"**Fix:** {f.recommendation}",
            "",
        ]
        if f.fix_sql:
            lines += ["```sql", f.fix_sql, "```", ""]
    if result.skipped:
        lines.append(
            "**Checks that could not run:** "
            + "; ".join(f"{k}: {v}" for k, v in result.skipped.items())
        )
        lines.append("")
    lines.append(
        f"_Generated by [FrostWatch]({REPO_URL}) v{__version__}, the open source Snowflake "
        "cost observability tool. Estimates are directional._"
    )
    return "\n".join(lines) + "\n"


def render_json(result: AuditResult) -> str:
    return json.dumps(result.to_dict(), indent=2)


def render(result: AuditResult, fmt: str) -> str:
    return {"html": render_html, "md": render_markdown, "json": render_json}[fmt](result)
